const $ = window.jQuery;
const fs = require('fs').promises;
const path = require('path');
const { ipcRenderer } = require('electron');
const state = require('./state');
const { getManualExcludes, getManualIncludes } = require('./filters');
const { updateConflictUI, showToast, syncSearchModeLabel, syncExtractUi } = require('./ui');
const { CONCATIGNORE_FILE } = require('./constants');
const { toInt } = require('./utils');

const stringArray = (value) => Array.isArray(value)
  ? value.filter((item) => typeof item === 'string' && item.trim())
  : [];

function buildConfig() {
  return {
    _comment: 'Auto-generated by Folder Concatenator. Edit carefully.',
    folders: state.folders.map((folder) => ({ path: folder.path, enabled: folder.enabled })),
    smartExcludes: [...state.smartExcludes],
    smartExcludesOff: [...state.seenNoise].filter((name) => !state.smartExcludes.has(name)),
    excludedFileTypes: [...state.excludedTypes],
    manualExcludes: getManualExcludes(),
    manualIncludes: getManualIncludes(),
    contentSearch: String($('#contentFilterInput').val() || ''),
    searchMode: $('#searchModeToggle').prop('checked') ? 'AND' : 'OR',
    wholeWord: $('#wholeWordToggle').prop('checked'),
    extract: {
      mode: $('#extractMode').val(),
      context: toInt($('#ctxLines').val(), 10),
      smallFile: toInt($('#smallFile').val(), 150),
      keepHead: toInt($('#keepHead').val(), 0),
      lineNumbers: $('#lineNumbers').prop('checked'),
    },
  };
}

const mergeCsv = (selector, existing, incoming) => {
  const values = [...new Set([...existing, ...incoming].map((value) => value.trim()).filter(Boolean))];
  $(selector).val(values.join(', '));
};

/** Merge a saved config into current UI/state, ignoring malformed optional values. */
async function applyConfig(config) {
  if (!config || typeof config !== 'object' || Array.isArray(config)) return;

  for (const folder of Array.isArray(config.folders) ? config.folders : []) {
    if (!folder || typeof folder.path !== 'string' || !folder.path.trim()) continue;
    const resolved = path.resolve(folder.path);
    if (state.folders.some((item) => path.resolve(item.path) === resolved)) continue;
    try {
      const stat = await fs.stat(resolved);
      if (!stat.isDirectory()) continue;
    } catch {
      continue;
    }
    state.folders.push({ path: resolved, enabled: folder.enabled !== false });
  }

  stringArray(config.smartExcludes).forEach((name) => {
    state.smartExcludes.add(name);
    state.seenNoise.add(name);
  });
  stringArray(config.smartExcludesOff).forEach((name) => {
    state.seenNoise.add(name);
    state.smartExcludes.delete(name);
  });
  stringArray(config.excludedFileTypes).forEach((extension) => {
    state.excludedTypes.add(extension.toLowerCase());
  });

  if (Array.isArray(config.manualExcludes)) {
    mergeCsv('#excludeInput', getManualExcludes(), stringArray(config.manualExcludes));
  }
  if (Array.isArray(config.manualIncludes)) {
    mergeCsv('#includeInput', getManualIncludes(), stringArray(config.manualIncludes));
  }
  if (typeof config.contentSearch === 'string') $('#contentFilterInput').val(config.contentSearch);
  $('#searchModeToggle').prop('checked', config.searchMode === 'AND');
  $('#wholeWordToggle').prop('checked', config.wholeWord === true);

  if (config.extract && typeof config.extract === 'object') {
    const extract = config.extract;
    if (['full', 'context', 'block'].includes(extract.mode)) $('#extractMode').val(extract.mode);
    if (extract.context != null) $('#ctxLines').val(toInt(extract.context, 10));
    if (extract.smallFile != null) $('#smallFile').val(toInt(extract.smallFile, 150));
    if (extract.keepHead != null) $('#keepHead').val(toInt(extract.keepHead, 0));
    if (extract.lineNumbers != null) $('#lineNumbers').prop('checked', extract.lineNumbers === true);
  }

  syncSearchModeLabel();
  syncExtractUi();
  updateConflictUI();
}

async function loadConfig(folderPath) {
  let raw;
  try {
    raw = await fs.readFile(path.join(folderPath, CONCATIGNORE_FILE), 'utf8');
  } catch {
    return null;
  }
  try {
    const config = JSON.parse(raw);
    if (!config || typeof config !== 'object' || Array.isArray(config)) throw new Error('Expected a JSON object');
    return config;
  } catch {
    showToast(`Invalid .concatignore in ${path.basename(folderPath)}`);
    return null;
  }
}

async function saveConfig() {
  const enabledFolders = state.folders.filter((folder) => folder.enabled);
  if (!enabledFolders.length) {
    alert('Please add at least one folder before saving a config.');
    return false;
  }

  try {
    const target = enabledFolders.length === 1
      ? enabledFolders[0].path
      : await ipcRenderer.invoke('pick-config-folder', enabledFolders.map((folder) => folder.path));
    if (!target) return false;

    await fs.writeFile(
      path.join(target, CONCATIGNORE_FILE),
      JSON.stringify(buildConfig(), null, 2),
      'utf8',
    );
    return true;
  } catch (error) {
    alert(`Failed to save config: ${error.message}`);
    return false;
  }
}

module.exports = { buildConfig, applyConfig, loadConfig, saveConfig };
